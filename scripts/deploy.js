/* Deploy Afterlife.
 *  Local test : npx hardhat node   (terminal 1)   then   npx hardhat run scripts/deploy.js --network localhost
 *               -> deploys a MockUSDC AT THE ARC USDC ADDRESS (hardhat_setCode), mints test funds, writes frontend/config.js
 *  Arc testnet: PRIVATE_KEY=0x... npx hardhat run scripts/deploy.js --network arcTestnet
 *  Arc mainnet: PRIVATE_KEY=0x... MIN_WINDOW=60 npx hardhat run scripts/deploy.js --network arcMainnet
 * The key is read from YOUR environment at run time; nothing is stored in the repo.
 */
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");

const ARC_USDC = "0x3600000000000000000000000000000000000000";
const NETS = {
  arcMainnet: { name: "Arc Mainnet", chainId: 5042, rpc: "https://rpc.mainnet.arc.io", explorer: "https://explorer.arc.io" },
  arcTestnet: { name: "Arc Testnet", chainId: 5042002, rpc: "https://rpc.testnet.arc.io", explorer: "https://explorer.testnet.arc.io" },
  localhost: { name: "Local test chain", chainId: 31337, rpc: "http://127.0.0.1:8545", explorer: "http://127.0.0.1:8545/#" },
};

async function main() {
  const net = NETS[network.name];
  if (!net) throw new Error("Use --network localhost | arcTestnet | arcMainnet");
  const [deployer] = await ethers.getSigners();
  if (!deployer) throw new Error("No signer. Set PRIVATE_KEY for Arc networks.");
  const local = network.name === "localhost";
  // Demo instances use a short minimum window so the whole flow fits in a video. Pick bigger for real use.
  const minWindow = Number(process.env.MIN_WINDOW || (local ? 5 : 60));
  console.log(`Network ${net.name} (chainId ${(await ethers.provider.getNetwork()).chainId}) deployer ${deployer.address} minWindow ${minWindow}s`);

  if (local) {
    const Mock = await ethers.getContractFactory("MockUSDC");
    const tmp = await Mock.deploy(); await tmp.waitForDeployment();
    const code = await ethers.provider.getCode(await tmp.getAddress());
    await network.provider.send("hardhat_setCode", [ARC_USDC, code]);
    const usdc = await ethers.getContractAt("MockUSDC", ARC_USDC);
    for (const s of (await ethers.getSigners()).slice(0, 5)) await (await usdc.mint(s.address, 1000n * 10n ** 6n)).wait();
    console.log("Mock USDC placed at", ARC_USDC, "and minted 1000 USDC to the first 5 accounts");
  }
  const feeOv = local ? {} : { maxFeePerGas: ethers.parseUnits("25", "gwei"), maxPriorityFeePerGas: 1n };
  const Af = await ethers.getContractFactory("Afterlife");
  const af = await Af.deploy(ARC_USDC, minWindow, feeOv);
  const tx = af.deploymentTransaction();
  await af.waitForDeployment();
  const addr = await af.getAddress();
  console.log("Afterlife deployed:", addr);
  console.log("Deploy tx:", tx.hash, `${net.explorer}/tx/${tx.hash}`);

  const cfg = { name: net.name, chainId: net.chainId, rpc: net.rpc, explorer: net.explorer, usdc: ARC_USDC, afterlife: addr, minFeeGwei: 20, currency: { name: "USDC", symbol: "USDC", decimals: 18 }, local };
  fs.writeFileSync(path.join(__dirname, "..", "frontend", "config.js"), "// generated by scripts/deploy.js\nwindow.AFTERLIFE_CONFIG = " + JSON.stringify(cfg, null, 2) + ";\n");
  console.log("Wrote frontend/config.js");
}
main().catch((e) => { console.error(e); process.exit(1); });
